// Submagic's implementation of CaptionRenderer.
//
// This is the translation boundary. Above it, everything speaks Clipiro:
// template slugs, our 13 render statuses, CaptionWord. Below it, everything
// speaks Submagic: template names, whatever status vocabulary they use, their
// word shape. Nothing leaks in either direction — that's what makes §43's
// eventual migration to a native renderer a file-swap rather than a rewrite.

